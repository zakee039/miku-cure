def normalize_language(language: str | None) -> str:
    return language if isinstance(language, str) and language in TEXTS else "zh"


def get_texts(language: str | None) -> dict[str, Any]:
    return TEXTS[normalize_language(language)]


def translate_progress(language: str | None, message: str) -> str:
    return get_texts(language)["progress"].get(message, message)


def environment_summary(language: str | None, report) -> str:
    texts = get_texts(language)
    passed = sum(1 for item in report.items if item.ok)
    state = texts["env_ready"] if report.all_required_ok else texts["env_problem"]
    return texts["env_summary"].format(
        passed=passed,
        total=len(report.items),
        state=state,
    )


def translate_environment_detail(language: str | None, detail: str) -> str:
    normalized = normalize_language(language)
    texts = get_texts(normalized)
    if normalized == "zh":
        return detail
    if detail.startswith("未找到：期望 "):
        return texts["env_missing_expected"].format(value=detail.removeprefix("未找到：期望 "))
    if detail.startswith("缺少 "):
        return texts["env_missing"].format(value=detail.removeprefix("缺少 "))
    if detail.endswith(" 个 .pth") and detail.removesuffix(" 个 .pth").isdigit():
        return texts["env_weight_count"].format(
            count=detail.removesuffix(" 个 .pth")
        )
    if detail == "可选，缺失时仅无动画":
        return texts["env_optional_animation"]
    if detail == "未检测":
        return texts["env_not_checked"]
    return detail
